async function loadNewsFromAPI() {
  try {
    const response = await fetch("https://tsp-news-backend.onrender.com/api/news/");

    if (!response.ok) {
      throw new Error(`API error: ${response.status}`);
    }

    const data = await response.json();

    console.log("Django API News:", data);

    return data.map(news => ({
      ...news,
      category: news.category_name || "மற்றவை",
      description: news.short_description || "",
      body: news.content || "",
      time: news.created_at
        ? new Date(news.created_at).toLocaleString("ta-IN")
        : ""
    }));

  } catch (error) {
    console.error("Could not load news from Django API:", error);

    return [];
  }
}